# Receptor atom types used by AutoDock4 for standard proteins
RECEPTOR_TYPES = "A C HD N NA OA SA"


def _write_ascii(path: str, content: str) -> None:
    """Write content to path using ASCII encoding (no BOM)."""
    with open(path, "w", encoding="ascii", errors="replace") as fh:
        fh.write(content)
    print(f"  [file_writer] Written: {path}")


def write_metals_dat(output_dir: str) -> str:
    """
    Write AD4_metals.dat into output_dir.
    This file supplies AutoDock4 with Lennard-Jones parameters for
    all supported heavy metals. It is referenced by both the GPF and DPF.

    Returns
    -------
    str : absolute path to the written file.
    """
    lines = ["# AD4_metals.dat --- Custom heavy metal parameters\n"
             "# Generated by SanjeevaniDock\n"
             "# Format: atom_par <TYPE> <Rii> <epsii> <vol> <solv>"
             "  0.0 0.0 0 -1 -1 1\n\n"]
    for metal, p in METAL_PARAMS.items():
        line = (
            f"atom_par {metal:<3} {p['Rii']:<6}  {p['epsii']:<6}  "
            f"{p['vol']:<7}  {p['solv']:<9}  "
            f"0.0  0.0  0  -1  -1  1    "
            f"# {p['comment']}\n"
        )
        lines.append(line)

    out_path = os.path.join(output_dir, "AD4_metals.dat")
    _write_ascii(out_path, "".join(lines))
    return out_path


def write_metal_pdbqt(output_dir: str, metal_code: str) -> str:
    """
    Write a single-atom PDBQT ligand file for the specified metal ion.

    Parameters
    ----------
    output_dir  : str   - working directory
    metal_code  : str   - one of CD, CU, HG, FE, ZN, PB

    Returns
    -------
    str : path to the written .pdbqt file.

    Notes
    -----
    We use coordinates (1.000, 1.000, 1.000) instead of (0, 0, 0) to
    avoid a division-by-zero in bond-angle calculations if the file is
    later re-read by AutoDockTools.

    We do NOT use prepare_ligand4.py here because PyBabel's hybridisation
    calculator requires at least two atoms and raises ZeroDivisionError
    on single-atom inputs.
    """
    metal_code = metal_code.upper()
    if metal_code not in METAL_PARAMS:
        raise ValueError(
            f"Unsupported metal: {metal_code}. "
            f"Supported: {list(METAL_PARAMS.keys())}"
        )

    p = METAL_PARAMS[metal_code]
    # PDBQT format is strictly fixed-width.
    # Columns: 1-6 record, 7-11 serial, 13-16 name, 18-20 resname,
    #          22 chain, 23-26 resseq, 31-38 x, 39-46 y, 47-54 z,
    #          55-60 occupancy, 61-66 tempfactor, 67-76 charge, 77-78 atom type
    hetatm_line = "{:<6}{:>5}  {:<4}{:<4}{:<1}{:>4}    {:>8.3f}{:>8.3f}{:>8.3f}{:>6.2f}{:>6.2f}    {:>6} {:<2}\n".format(
        "HETATM",        # record type
        1,               # serial number
        metal_code,      # atom name
        metal_code,      # residue name
        "A",             # chain
        1,               # residue sequence number
        1.000,           # x
        1.000,           # y
        1.000,           # z
        1.00,            # occupancy
        0.00,            # temp factor
        p['charge'],     # partial charge
        metal_code       # atom type
    )

    content = (
        f"REMARK  Metal Ion Ligand --- generated by SanjeevaniDock\n"
        f"REMARK  {p['comment']}\n"
        f"ROOT\n"
        + hetatm_line +
        f"ENDROOT\n"
        f"TORSDOF 0\n"
    )

    filename  = f"{metal_code.lower()}.pdbqt"
    out_path  = os.path.join(output_dir, filename)
    _write_ascii(out_path, content)
    return out_path


def write_gpf(
    output_dir:   str,
    protein_stem: str,
    metal_code:   str,
    center:       tuple,
    grid_config:  dict = None,
) -> str:
    """
    Write an AutoGrid parameter file (.gpf).

    Parameters
    ----------
    output_dir   : str  - working directory
    protein_stem : str  - protein name without extension (e.g. "smtA")
    metal_code   : str  - e.g. "CD"
    center       : tuple - (x, y, z) grid center; pass ("auto","","") for blind
    grid_config  : dict - optional, keys:
                          "box_size" : tuple of 3 floats, default (60, 60, 60)
                          "spacing"  : float, default 0.375

    Returns
    -------
    str : path to the written .gpf file.
    """
    if grid_config is None:
        grid_config = {}

    box_size = grid_config.get("box_size", (60, 60, 60))
    spacing  = grid_config.get("spacing", 0.375)

    metal_code = metal_code.upper()
    stem       = f"{protein_stem}_{metal_code.lower()}"
    npts       = tuple(round(s / spacing) for s in box_size)

    if center[0] == "auto":
        gridcenter_line = (
            "gridcenter auto                   "
            "# centred on protein centroid"
        )
    else:
        gridcenter_line = (
            f"gridcenter {center[0]:.3f} {center[1]:.3f} {center[2]:.3f}"
            f"    # mean CYS SG centroid"
        )

    content = (
        f"# GPF generated by SanjeevaniDock\n"
        f"npts {npts[0]} {npts[1]} {npts[2]}              "
        f"# grid points ({box_size[0]} A / {spacing})\n"
        f"gridfld {stem}.maps.fld\n"
        f"spacing {spacing}\n"
        f"parameter_file AD4_metals.dat        "
        f"# custom heavy metal parameters\n"
        f"receptor_types {RECEPTOR_TYPES}      "
        f"# standard protein atom types\n"
        f"ligand_types {metal_code}            # metal atom type\n"
        f"receptor {protein_stem}.pdbqt\n"
        f"{gridcenter_line}\n"
        f"smooth 0.5\n"
        f"map {stem}.{metal_code}.map\n"
        f"elecmap {stem}.e.map\n"
        f"dsolvmap {stem}.d.map\n"
        f"dielectric -0.1465\n"
    )

    out_path = os.path.join(output_dir, f"{stem}.gpf")
    _write_ascii(out_path, content)
    return out_path


def write_dpf(
    output_dir:   str,
    protein_stem: str,
    metal_code:   str,
    ga_runs:      int = 50,
) -> str:
    """
    Write an AutoDock docking parameter file (.dpf).

    Parameters
    ----------
    output_dir   : str - working directory
    protein_stem : str - protein name without extension
    metal_code   : str - e.g. "CD"
    ga_runs      : int - number of Lamarckian GA runs (default 50)

    Returns
    -------
    str : path to the written .dpf file.
    """
    metal_code = metal_code.upper()
    stem       = f"{protein_stem}_{metal_code.lower()}"

    content = (
        f"# DPF generated by SanjeevaniDock\n"
        f"autodock_parameter_version 4.2\n"
        f"outlev 1\n"
        f"intelec\n"
        f"seed pid time\n"
        f"parameter_file AD4_metals.dat\n"
        f"ligand_types {metal_code}\n"
        f"fld {stem}.maps.fld\n"
        f"map {stem}.{metal_code}.map\n"
        f"elecmap {stem}.e.map\n"
        f"dsolvmap {stem}.d.map\n"
        f"move {metal_code.lower()}.pdbqt\n"
        f"about 1.0 1.0 1.0\n"
        f"tran0 random\n"
        f"quaternion0 random\n"
        f"dihe0 random\n"
        f"tstep 2.0\n"
        f"qstep 50.0\n"
        f"dstep 50.0\n"
        f"torsdof 0\n"
        f"rmstol 2.0\n"
        f"extnrg 1000.0\n"
        f"e0max 0.0 10000\n"
        f"ga_pop_size 150\n"
        f"ga_num_evals 2500000\n"
        f"ga_num_generations 27000\n"
        f"ga_elitism 1\n"
        f"ga_mutation_rate 0.02\n"
        f"ga_crossover_rate 0.8\n"
        f"ga_window_size 10\n"
        f"ga_cauchy_alpha 0.0\n"
        f"ga_cauchy_beta 1.0\n"
        f"set_ga\n"
        f"sw_max_its 300\n"
        f"sw_max_succ 4\n"
        f"sw_max_fail 4\n"
        f"sw_rho 1.0\n"
        f"sw_lb_rho 0.01\n"
        f"ls_search_freq 0.06\n"
        f"set_psw1\n"
        f"unbound_model bound\n"
        f"ga_run {ga_runs}\n"
        f"analysis\n"
    )

    out_path = os.path.join(output_dir, f"{stem}.dpf")
    _write_ascii(out_path, content)
    return out_path
