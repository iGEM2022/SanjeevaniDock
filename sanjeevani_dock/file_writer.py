"""
file_writer.py
--------------
Generates all input files needed for an AutoDock4 run:
  - AD4_metals.dat  : custom Lennard-Jones parameters for heavy metals
  - <metal>.pdbqt   : single-atom ligand file (written manually because
                      prepare_ligand4.py raises ZeroDivisionError on
                      single-atom inputs)
  - <protein>_<metal>.gpf : AutoGrid parameter file
  - <protein>_<metal>.dpf : AutoDock docking parameter file


All files are written with ASCII encoding (no UTF-8 BOM) because a
BOM at byte 0 causes a parse error in AutoDockTools.
"""


